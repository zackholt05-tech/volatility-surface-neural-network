"""Hard-constrained neural surface: a price-space mixture of eSSVI surfaces whose knot parameters
are generated by a network of maturity.

Each component j is an eSSVI surface built by ``knots_from_rates``, so it is free of calendar and
butterfly arbitrage for any rates. With the generator "mlp", the rates at every quoted maturity
are the output of a small network of log T (one head of three rates per component), which ties
the term structure together; with "free", each knot has its own rates.

Components are mixed in forward-normalized price space with weights pi_j fixed across maturities:

    c(k, T) = sum_j pi_j c_BS(k, w_j(k, T)).

A convex combination of arbitrage-free call price surfaces is arbitrage-free: convexity and
monotonicity in strike, the price bounds, and monotonicity in T at fixed log-forward moneyness are
all preserved by nonnegative weights that do not depend on T. The model's total variance is the
Black implied total variance of the mixture price, obtained by a bracketed log-price Newton solve
(the mixture vol lies between the smallest and largest component vols). During fitting, gradients
pass through the inversion by implicit differentiation, d sigma = d c / vega.
"""

from __future__ import annotations

import copy
from dataclasses import dataclass

import numpy as np
import torch
from torch import nn
from torch.special import log_ndtr

from volsurf.eval.dayset import FitData
from volsurf.models.base import W_FLOOR, SurfaceModel
from volsurf.models.essvi import (
    ESSVISurface,
    essvi_w,
    interp_knots,
    knots_from_rates,
    rates_from_knots,
)
from volsurf.pricing.black76 import log_otm_price, total_vol_from_log_price


@dataclass
class NeuralESSVIConfig:
    components: int = 3
    generator: str = "mlp"  # "mlp": rates from a network of log T; "free": rates per knot
    hidden: tuple[int, ...] = (32, 32)
    init_scales: tuple[float, ...] = (1.0, 1.8, 0.6)  # theta multipliers seeding the components
    init_weight: float = 0.8  # initial weight of the first component (matched to an eSSVI fit)
    pretrain_steps: int = 500  # Adam steps fitting the network to the seed rates (cold start)
    steps: int = 200  # Adam steps on the data before L-BFGS
    lr: float = 1e-2
    lbfgs_iters: int = 500
    warm_steps: int = 0
    warm_lbfgs_iters: int = 300


def _log1mexp_torch(x):
    """log(1 - exp(x)) for x < 0; each branch only sees inputs where it is used, so the unused
    branch cannot leak infinite gradients through ``torch.where``."""
    cut = -np.log(2.0)
    near = torch.clamp(x, min=cut, max=-1e-300)
    far = torch.clamp(x, max=cut)
    return torch.where(x > cut, torch.log(-torch.expm1(near)), torch.log1p(-torch.exp(far)))


def _log_otm_price_torch(k, w):
    """Log normalized OTM price (call for k >= 0, put for k < 0), finite far into the wings where
    the price itself underflows; torch mirror of ``black76.log_otm_price``."""
    v = torch.sqrt(w)
    d1 = -k / v + 0.5 * v
    d2 = d1 - v
    log_a = torch.where(k >= 0, log_ndtr(d1), k + log_ndtr(-d2))
    log_b = torch.where(k >= 0, k + log_ndtr(d2), log_ndtr(-d1))
    return log_a + _log1mexp_torch(log_b - log_a)


def mixture_total_variance(k, w_components, weights):
    """Implied total variance of a price-space mixture; ``w_components`` has shape (M, ...)."""
    w_components = np.maximum(w_components, W_FLOOR)
    log_p = np.log(weights).reshape((-1,) + (1,) * k.ndim) + log_otm_price(k, w_components)
    log_mix = np.logaddexp.reduce(log_p, axis=0)
    v = np.sqrt(w_components)
    return total_vol_from_log_price(log_mix, k, v.min(axis=0), v.max(axis=0)) ** 2


class NeuralESSVISurface(SurfaceModel):
    name = "nessvi"

    def __init__(self, cfg: NeuralESSVIConfig | None = None, seed: int = 0) -> None:
        super().__init__()
        self.cfg = cfg or NeuralESSVIConfig()
        self.seed = seed
        if self.cfg.generator not in ("mlp", "free"):
            raise ValueError(f"unknown generator {self.cfg.generator!r}")

    # ---- parameter generation -------------------------------------------------------------

    def _make_net(self) -> nn.Module:
        layers, width = [], 1
        for h in self.cfg.hidden:
            layers += [nn.Linear(width, h), nn.Tanh()]
            width = h
        layers.append(nn.Linear(width, 3 * self.cfg.components))
        return nn.Sequential(*layers).double()

    def _rates(self, x_T) -> torch.Tensor:
        """Rates of shape (M, n_knots, 3)."""
        M = self.cfg.components
        if self.cfg.generator == "free":
            return self.free_rates
        out = self.net(x_T[:, None])  # (n_knots, 3M)
        return out.reshape(-1, M, 3).permute(1, 0, 2)

    def _component_knots(self, knot_T, x_T):
        rates = self._rates(x_T)
        return [knots_from_rates(knot_T, rates[j], lib=torch) for j in range(self.cfg.components)]

    def _seed_rates(self, data: FitData, knot_T: np.ndarray, init) -> np.ndarray:
        """Target rates (M, n_knots, 3) for initialization."""
        M = self.cfg.components
        if init is not None:  # previous day's surface, re-knotted at today's maturities
            return np.stack(
                [
                    rates_from_knots(knot_T, *interp_knots(knot_T, init.knot_T, *kn))
                    for kn in init.knots
                ]
            )
        ess = ESSVISurface().fit(data)
        scales = (tuple(self.cfg.init_scales) + (1.0,) * M)[:M]
        out = []
        for c in scales:
            wing = min(c, 1.5)
            out.append(
                rates_from_knots(knot_T, ess.theta * c, ess.u_plus * wing, ess.u_minus * wing)
            )
        return np.stack(out)

    # ---- fitting ---------------------------------------------------------------------------

    def fit(self, data: FitData, init: NeuralESSVISurface | None = None) -> NeuralESSVISurface:
        cfg, M = self.cfg, self.cfg.components
        torch.manual_seed(self.seed)
        knot_np = np.asarray(data.slice_T, dtype=float)
        knot_T = torch.as_tensor(knot_np)
        warm = init is not None

        if warm and cfg.generator == "mlp":
            self.net = copy.deepcopy(init.net)
            self._mu, self._sd = init._mu, init._sd
            self.logits = init.logits.detach().clone().requires_grad_(True)
        else:
            log_T = np.log(knot_np)
            self._mu, self._sd = float(log_T.mean()), float(max(log_T.std(), 0.1))
            targets = torch.as_tensor(self._seed_rates(data, knot_np, init))
            if cfg.generator == "free":
                self.free_rates = targets.clone().requires_grad_(True)
            else:
                self.net = self._make_net()
            if warm:
                self.logits = init.logits.detach().clone().requires_grad_(True)
            else:
                rest = (1.0 - cfg.init_weight) / max(M - 1, 1)
                start = np.log([cfg.init_weight] + [rest] * (M - 1))
                self.logits = torch.tensor(start, dtype=torch.float64, requires_grad=True)
        x_T = (torch.log(knot_T) - self._mu) / self._sd

        if cfg.generator == "mlp" and not warm:
            opt = torch.optim.Adam(self.net.parameters(), lr=1e-2)
            for _ in range(cfg.pretrain_steps):
                opt.zero_grad()
                loss = torch.mean((self._rates(x_T) - targets) ** 2)
                loss.backward()
                opt.step()

        params = [self.free_rates] if cfg.generator == "free" else list(self.net.parameters())
        if M > 1:
            params.append(self.logits)

        k = torch.as_tensor(data.k)
        T = torch.as_tensor(data.T)
        sid = torch.as_tensor(data.slice_id)
        iv = torch.as_tensor(data.iv)
        s = torch.as_tensor(data.s)

        def objective():
            knots = self._component_knots(knot_T, x_T)
            w = torch.stack([essvi_w(k, th[sid], up[sid], um[sid]) for th, up, um in knots])
            w = torch.clamp(w, min=W_FLOOR)
            if M == 1:
                model_iv = torch.sqrt(w[0] / T)
            else:
                log_pi = torch.log_softmax(self.logits, 0)
                log_p = torch.logsumexp(log_pi[:, None] + _log_otm_price_torch(k, w), dim=0)
                w_mix = mixture_total_variance(
                    data.k, w.detach().numpy(), log_pi.detach().exp().numpy()
                )
                v = torch.as_tensor(np.sqrt(w_mix))
                # d v = d log P / (d log P / d v) with d log P / d v = n(d1) / P, in log space so
                # it stays finite where both the price and n(d1) underflow
                d1 = -k / v + 0.5 * v
                log_slope = -0.5 * d1 * d1 - 0.5 * np.log(2.0 * np.pi) - log_p.detach()
                model_iv = (v + (log_p - log_p.detach()) * torch.exp(-log_slope)) / torch.sqrt(T)
            return torch.mean(((model_iv - iv) / s) ** 2)

        steps = cfg.warm_steps if warm else cfg.steps
        if steps:
            opt = torch.optim.Adam(params, lr=cfg.lr / 10 if warm else cfg.lr)
            for _ in range(steps):
                opt.zero_grad()
                loss = objective()
                loss.backward()
                opt.step()

        lbfgs = torch.optim.LBFGS(
            params,
            max_iter=cfg.warm_lbfgs_iters if warm else cfg.lbfgs_iters,
            history_size=50,
            line_search_fn="strong_wolfe",
            tolerance_grad=1e-10,
            tolerance_change=1e-14,
        )

        def closure():
            lbfgs.zero_grad()
            loss = objective()
            loss.backward()
            return loss

        lbfgs.step(closure)
        with torch.no_grad():
            self.final_loss = float(objective())
            self.knots = [
                tuple(t.numpy().copy() for t in kn) for kn in self._component_knots(knot_T, x_T)
            ]
            self.weights = torch.softmax(self.logits, 0).numpy().copy()
        if not np.isfinite(self.final_loss):
            self.n_failed += 1
        self.knot_T = knot_np
        return self

    # ---- evaluation ------------------------------------------------------------------------

    def w(self, k, T) -> np.ndarray:
        k, T = np.broadcast_arrays(np.asarray(k, dtype=float), np.asarray(T, dtype=float))
        comps = np.stack([essvi_w(k, *interp_knots(T, self.knot_T, *kn)) for kn in self.knots])
        if len(self.knots) == 1:
            return comps[0]
        return mixture_total_variance(k, comps, self.weights)
